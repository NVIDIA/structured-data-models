import pytest
import torch
from torch import Tensor

from sdm import TableTensor
from sdm.models.kumo.timeseries.anomaly import MACSThreshold, SCSThreshold
from sdm.testing import withCUDA


def _series(
    kind: str, device: torch.device, dtype: torch.dtype
) -> tuple[Tensor, Tensor]:
    """Make fixed scores and targets used for upstream decision fixtures."""
    time = torch.arange(600, device=device, dtype=dtype)
    target = torch.stack(
        [1 + 0.1 * (time / 20).sin(), 1 + 0.1 * (time / 17).cos()], dim=-1
    )
    scores = 0.1 + 0.02 * (time / 7).sin().square()
    if kind == "regimes":
        target[200:400] += 9
        target[400:] += 2
        scores[200:400] += 0.4
        scores[400:] += 0.1
    elif kind == "oscillating":
        target -= 1
    scores[[0, 50, 151, 199, 200, 201, 299, 398, 400, 450, 599]] += 2
    return scores, target


@withCUDA
@pytest.mark.parametrize("dtype", [torch.float32, torch.float64])
@pytest.mark.parametrize("kind", ["flat", "regimes", "oscillating"])
@pytest.mark.parametrize("as_table", [False, True])
def test_threshold_upstream_decisions(
    device: torch.device, dtype: torch.dtype, kind: str, as_table: bool
) -> None:
    """Match flags from pinned Kumo-TS, including segment-boundary behavior."""
    # Expected indices generated by the unmodified threshold algorithms in
    # NVIDIA/Kumo-TS af74798, using the SDK wrappers' SCS/MACS defaults.
    scores, target = _series(kind, device, dtype)
    all_spikes = [50, 151, 199, 200, 201, 299, 398, 400, 450, 599]
    scs_spikes = (
        all_spikes
        if kind == "oscillating"
        else [50, 151, 199, 299, 398, 450, 599]
    )
    scs = SCSThreshold()(
        scores, TableTensor.from_tensor(target) if as_table else target
    )
    macs = MACSThreshold()(scores)
    for actual, indices in ((scs, scs_spikes), (macs, all_spikes)):
        expected = torch.zeros(600, device=device, dtype=torch.bool)
        expected[indices] = True
        assert actual.device == device
        assert actual.dtype == torch.bool
        assert not actual.requires_grad
        torch.testing.assert_close(actual, expected)


@withCUDA
@pytest.mark.parametrize("length", [0, 1, 2, 37, 200, 401])
@pytest.mark.parametrize("value", [0.0, 1.0, 1e7])
def test_constant_scores(
    device: torch.device, length: int, value: float
) -> None:
    """Strict global percentile filtering never flags constant scores."""
    scores = torch.full((length,), value, device=device)
    target = torch.ones(length, 2, device=device)
    for flags in (SCSThreshold()(scores, target), MACSThreshold()(scores)):
        assert flags.shape == (length,)
        assert flags.device == device
        assert not flags.any()


@withCUDA
@pytest.mark.parametrize(
    ("confidence", "first"), [(0.85, 2), (0.9, 7), (0.95, 7), (0.99, 20)]
)
def test_confidence_width(
    device: torch.device, confidence: float, first: int
) -> None:
    """Retain the SDK's discrete width multipliers, not a quantile model."""
    scores = torch.arange(20, device=device, dtype=torch.float64)
    target = torch.ones(20, 2, device=device)
    expected = scores >= first
    scs = SCSThreshold(confidence_level=confidence, percentile_filter=0)
    macs = MACSThreshold(confidence_level=confidence, percentile_filter=0)
    torch.testing.assert_close(scs(scores, target), expected)
    torch.testing.assert_close(macs(scores), expected)


@withCUDA
@pytest.mark.parametrize(
    ("confidence", "percentile", "minimum", "indices"),
    [
        (0.99, 95, 50, [50, 149, 199, 200, 201, 299, 374, 398, 400, 450, 599]),
        (0.85, 95, 25, [50, 199, 200, 201, 299, 398, 400, 450, 599]),
        (0.99, 99, 50, [199, 200, 201, 299]),
    ],
)
def test_apca_regime_changes(
    device: torch.device,
    confidence: float,
    percentile: float,
    minimum: int,
    indices: list[int],
) -> None:
    """Match upstream splits away from the flat-data 200-row boundaries."""
    time = torch.arange(600, device=device, dtype=torch.float64)
    target = torch.stack(
        [1 + 0.1 * (time / 20).sin(), 1 + 0.1 * (time / 17).cos()], dim=-1
    )
    target[150:375] += 9
    target[375:] += 2
    scores = 0.1 + 0.02 * (time / 7).sin().square()
    scores[150:375] += 0.4
    scores[375:] += 0.1
    scores[
        [
            0,
            50,
            149,
            150,
            151,
            199,
            200,
            201,
            299,
            374,
            375,
            376,
            398,
            400,
            450,
            599,
        ]
    ] += 2
    expected = torch.zeros(600, device=device, dtype=torch.bool)
    expected[indices] = True
    threshold = SCSThreshold(
        confidence_level=confidence,
        percentile_filter=percentile,
        min_segment_size=minimum,
    )
    torch.testing.assert_close(threshold(scores, target), expected)


@withCUDA
def test_default_percentile_filters(device: torch.device) -> None:
    """SCS and MACS retain their distinct 95th and 97th percentile filters."""
    scores = torch.arange(100, device=device, dtype=torch.float64)
    scs = SCSThreshold(confidence_level=0.95)
    torch.testing.assert_close(
        scs(scores, torch.ones(100, 1, device=device)), scores >= 95
    )
    torch.testing.assert_close(MACSThreshold()(scores), scores >= 97)


@withCUDA
def test_strict_percentile_ties(device: torch.device) -> None:
    """Scores equal to the percentile cutoff are not flagged as anomalies."""
    scores = torch.ones(100, device=device)
    scores[20:40] = 10
    target = torch.ones(100, 2, device=device)
    assert not SCSThreshold()(scores, target).any()
    assert not MACSThreshold()(scores).any()
    assert SCSThreshold(percentile_filter=70)(scores, target).any()
    assert MACSThreshold(percentile_filter=70)(scores).any()


@pytest.mark.parametrize("value", [float("nan"), float("inf")])
def test_nonfinite_scores(value: float) -> None:
    """Reject invalid scores rather than silently marking everything normal."""
    scores = torch.tensor([1.0, value])
    with pytest.raises(ValueError, match="finite scores"):
        SCSThreshold()(scores, torch.ones(2, 1))
    with pytest.raises(ValueError, match="finite scores"):
        MACSThreshold()(scores)
    with pytest.raises(ValueError, match="finite target"):
        SCSThreshold()(torch.ones(2), scores[:, None])


@pytest.mark.parametrize("shape", [(4,), (3, 2), (4, 0)])
def test_target_alignment(shape: tuple[int, ...]) -> None:
    """Reject targets whose rows or features cannot align with the scores."""
    with pytest.raises(ValueError, match="matching scores"):
        SCSThreshold()(torch.ones(4), torch.ones(shape))


def test_score_shape() -> None:
    """Do not silently threshold across batch or feature dimensions."""
    scores = torch.ones(4, 1)
    with pytest.raises(ValueError, match="shape"):
        SCSThreshold()(scores, torch.ones(4, 2))
    with pytest.raises(ValueError, match="shape"):
        MACSThreshold()(scores)


def test_segment_size() -> None:
    """Require an APCA split to advance by at least one observation."""
    with pytest.raises(ValueError, match="min_segment_size"):
        SCSThreshold(min_segment_size=0)
    with pytest.raises(ValueError, match="long_window"):
        MACSThreshold(long_window=0)
